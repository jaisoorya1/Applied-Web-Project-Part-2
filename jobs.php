                <h2>SOC Analyst</h2>
                <aside>reference code: SOC026</aside>
                <p style="margin-bottom: 15px"><span style="font-size: 1.2rem; color: var(--accent-color); text-transform: uppercase; letter-spacing: 2px; margin-bottom: 15px;"><strong>Employment Type: </strong></span>Full-time</p>
                <p style="margin-bottom: 15px"><span style="font-size: 1.2rem; color: var(--accent-color); text-transform: uppercase; letter-spacing: 2px; margin-bottom: 15px;"><strong>Salary: </strong></span>$85,000–$120,000 + superannuation, depending on experience</p>
                <h3 style="margin-bottom: 5px">Description:</h3>
                <p style="margin-bottom: 15px">We are seeking a SOC Analyst to monitor, investigate and respond to cybersecurity threats across our technology environment. You will work with SIEM, EDR/XDR and other security tools to identify threats, investigate incidents and support continuous improvement of our security operations.</p>
                
                
                <details>
                    <summary style="margin-bottom: 15px">Read more</summary>
                    <h3 style="margin-bottom: 5px">Key Responsibilities</h3>
                    <details>
                        <summary style="margin-bottom: 15px">Expand</summary>
                        <ul style="margin-left: 15px">
                            <li>Monitor and triage security alerts and events.</li>
                            <li>Investigate phishing, malware, suspicious activity and potential breaches.</li>
                            <li>Perform initial incident response, containment and escalation.</li>
                            <li>Analyse logs and security events across networks, endpoints and cloud environments.</li>
                            <li>Use SIEM, EDR/XDR and threat-intelligence tools.</li>
                            <li>Document incidents and maintain accurate investigation records.</li>
                            <li>Support threat hunting, detection tuning and security improvements.</li>
                            <li style="margin-bottom: 15px">Escalate high-risk incidents to senior security or technical teams.</li>
                        </ul>
                    </details>
                    <h3 style="margin-bottom: 5px">Essential Requirements</h3>
                    <details>
                        <summary style="margin-bottom: 15px">Expand</summary>
                        <ul style="margin-left: 15px">
                            <li>Relevant experience or qualifications in Cybersecurity, IT, Computer Science or a related field.</li>
                            <li>Experience in SOC, cybersecurity, IT security or a similar role.</li>
                            <li>Good understanding of networking, Windows/Linux and cybersecurity fundamentals.</li>
                            <li>Experience with a SIEM platform such as Microsoft Sentinel, Splunk or QRadar.</li>
                            <li>Understanding of EDR/XDR and incident-response processes.</li>
                            <li>Familiarity with MITRE ATT&CK and common cyber attack techniques.</li>
                            <li style="margin-bottom: 15px">Strong analytical, problem-solving and communication skills.</li>
                        </ul>
                    </details>
                    <h3 style="margin-bottom: 5px">Preferable Requirements</h3>
                    <details>
                        <summary style="margin-bottom: 15px">Expand</summary>
                        <ol style="margin-left: 15px">
                            <li>1–3+ years' SOC/cybersecurity experience.</li>
                            <li>Experience with Microsoft Sentinel, Defender, Splunk, CrowdStrike or similar.</li>
                            <li>Knowledge of Azure/AWS security.</li>
                            <li>Experience with KQL, SPL, Python, PowerShell or Bash.</li>
                            <li>Cybersecurity certifications such as Security+, CySA+, GIAC or CISSP.</li>
                            <li>Knowledge of Essential Eight, NIST or ISO 27001.</li>
                            <li style="margin-bottom: 15px">Threat-hunting or digital-forensics experience.</li>
                        </ol>
                    </details>
                    <aside>The SOC Analyst reports directly to the SOC Manager and is part of the broader Cybersecurity function. The role works closely with Cybersecurity, IT, and other relevant teams to monitor security events, identify and investigate potential threats, and support the timely response and resolution of security incidents. The SOC Analyst will also collaborate with internal stakeholders to strengthen security monitoring, improve incident response processes, and contribute to the organisation’s overall cybersecurity posture.</aside>
                </details>
            </section>

