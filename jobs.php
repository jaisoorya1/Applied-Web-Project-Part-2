                            <li>Hands-on experience with EDR/XDR and SIEM platforms.</li>
                            <li>Strong knowledge of Windows and Linux environments.</li>
                            <li>Good understanding of networking, Active Directory and cloud security.</li>
                            <li>Experience investigating malware, phishing, credential compromise and unauthorised access.</li>
                            <li>Familiarity with MITRE ATT&CK and common attack techniques.</li>
