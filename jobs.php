                <h2>Penetration Tester</h2>
                <aside>reference code: PEN026</aside>
                <p style="margin-bottom: 15px"><span style="font-size: 1.2rem; color: var(--accent-color); text-transform: uppercase; letter-spacing: 2px; margin-bottom: 15px;"><strong>Employment Type: </strong></span>Full-time</p>
                <p style="margin-bottom: 15px"><span style="font-size: 1.2rem; color: var(--accent-color); text-transform: uppercase; letter-spacing: 2px; margin-bottom: 15px;"><strong>Salary: </strong></span>$100,000–$145,000 + superannuation, depending on experience</p>
                <h3 style="margin-bottom: 5px">Description:</h3>
                <p style="margin-bottom: 15px">We are seeking a skilled Penetration Tester to identify and assess security weaknesses across applications, networks, infrastructure and cloud environments. You will conduct authorised security testing, validate vulnerabilities and provide practical recommendations to strengthen our security posture.</p>
                
                
                <details>
                    <summary style="margin-bottom: 15px">Read more</summary>
                    <h3 style="margin-bottom: 5px">Key Responsibilities</h3>
                    <details>
                        <summary style="margin-bottom: 15px">Expand</summary>
                        <ul style="margin-left: 15px">
                            <li>Conduct authorised penetration tests across networks, systems, applications and cloud environments.</li>
                            <li>Identify, validate and assess security vulnerabilities and misconfigurations.</li>
                            <li>Perform web application, API, network and infrastructure security testing.</li>
                            <li>Conduct vulnerability exploitation and controlled proof-of-concept testing.</li>
                            <li>Perform reconnaissance, enumeration and security assessments.</li>
                            <li>Analyse findings and determine risk and potential business impact.</li>
                            <li>Prepare clear technical reports and remediation recommendations.</li>
                            <li>Present findings to technical and non-technical stakeholders.</li>
                            <li>Work with engineering and security teams to validate remediation.</li>
                            <li>Conduct retesting to confirm vulnerabilities have been resolved.</li>
                            <li>Maintain awareness of emerging vulnerabilities, attack techniques and security tools.</li>
                            <li style="margin-bottom: 15px">Contribute to improving penetration-testing methodologies, tooling and processes.</li>
                        </ul>
                    </details>
                    <h3 style="margin-bottom: 5px">Essential Requirements</h3>
                    <details>
                        <summary style="margin-bottom: 15px">Expand</summary>
                        <ul style="margin-left: 15px">
                            <li>Relevant experience in Penetration Testing, Offensive Security, Cybersecurity or a related field.</li>
                            <li>Hands-on experience conducting penetration tests in authorised environments.</li>
                            <li>Strong understanding of networking, operating systems, web applications and common attack techniques.</li>
                            <li>Experience with tools such as Burp Suite, Nmap, Metasploit and Kali Linux.</li>
                            <li>Understanding of OWASP Top 10 and common web application vulnerabilities.</li>
                            <li>Ability to identify, validate and clearly document security findings.</li>
                            <li>Strong analytical, problem-solving and technical writing skills.</li>
                            <li style="margin-bottom: 15px">Excellent communication and stakeholder-management skills.</li>
                        </ul>
                    </details>
                    <h3 style="margin-bottom: 5px">Preferable Requirements</h3>
                    <details>
                        <summary style="margin-bottom: 15px">Expand</summary>
                        <ol style="margin-left: 15px">
                            <li>2–4+ years' experience in penetration testing or offensive security.</li>
                            <li>Experience with web applications, APIs, Active Directory, cloud and mobile applications.</li>
                            <li>Knowledge of Azure/AWS security.</li>
                            <li>Experience with red teaming, adversary simulation or vulnerability research.</li>
                            <li>Scripting/programming skills in Python, PowerShell, Bash, JavaScript or similar.</li>
                            <li>Experience with Active Directory exploitation and privilege escalation.</li>
                            <li>Certifications such as OSCP, OSWE, OSEP, PNPT, CREST or GPEN.</li>
                            <li>Knowledge of MITRE ATT&CK, PTES and OWASP testing methodologies.</li>
                            <li>Experience producing client-facing penetration-test reports.</li>
                            <li style="margin-bottom: 15px">Australian Government security clearance, where applicable.</li>
                        </ol>
                    </details>
                    <aside>The Penetration Tester reports directly to the Offensive Security Manager and is part of the broader Cybersecurity function. The role works closely with Cybersecurity, IT, application development, and infrastructure teams to identify and assess security vulnerabilities across the organisation. The Penetration Tester will collaborate with key stakeholders to communicate findings, support remediation efforts, and contribute to improving the organisation’s overall security posture.</aside>
                </details>
