                            <li>Experience with Microsoft Defender, Sentinel, CrowdStrike, Splunk or similar platforms.</li>
                            <li>Digital forensics and malware-analysis experience.</li>
                            <li>Threat-hunting experience.</li>
                            <li>Experience with Azure/AWS security investigations.</li>
                            <li>Scripting skills in PowerShell, Python or Bash.</li>
                            <li>Knowledge of NIST, ISO 27001 and Essential Eight.</li>
                            <li>Certifications such as GCIH, GCFA, GCIA, CISSP or equivalent.</li>
